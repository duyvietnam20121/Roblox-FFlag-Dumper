#pragma once
// ---------------------------------------------------------------------------
// Output.hpp - serialises a DumpResult to FFlags.json / FFlags.hpp.
//
//  * JSON keeps the real flag names (properly escaped).
//  * The C++ header sanitises names into valid, unique identifiers and uses
//    `inline constexpr`, so it can be included from several TUs.
//  * Entries are sorted by name, so two dumps can be compared with a plain diff.
// ---------------------------------------------------------------------------

#include <cctype>
#include <cstdio>
#include <ctime>
#include <filesystem>
#include <fstream>
#include <set>
#include <string>
#include <string_view>
#include <vector>

#include "Memory.hpp"
#include "Scanner.hpp"

namespace Output {

struct Meta {
    std::string process;
    std::string robloxVersion = "unknown";  // e.g. version-5a21b87bbc2641cf
    std::string generatedAt;                // "2026-11-03 05:06:00 UTC"
    std::size_t imageSize = 0;
};

// Current date/time in UTC, e.g. "2026-11-03 05:06:00 UTC".
[[nodiscard]] inline std::string Timestamp() {
    const std::time_t now = std::time(nullptr);
    std::tm utc{};
    gmtime_s(&utc, &now);
    char text[32]{};
    std::strftime(text, sizeof(text), "%Y-%m-%d %H:%M:%S UTC", &utc);
    return text;
}

// Roblox installs every build into a folder named "version-<hash>", e.g.
// .../Versions/version-5a21b87bbc2641cf/RobloxPlayerBeta.exe -> "version-5a21b87bbc2641cf".
// Returns "unknown" when the exe does not live in such a folder.
[[nodiscard]] inline std::string RobloxVersionFromPath(const std::wstring& exePath) {
    constexpr std::string_view kPrefix = "version-";
    const std::string folder = std::filesystem::path(exePath).parent_path().filename().string();
    if (folder.size() > kPrefix.size() && folder.compare(0, kPrefix.size(), kPrefix) == 0) return folder;
    return "unknown";
}

[[nodiscard]] inline std::string JsonEscape(const std::string& text) {
    std::string out;
    out.reserve(text.size());
    for (const unsigned char c : text) {
        switch (c) {
            case '"':  out += "\\\""; break;
            case '\\': out += "\\\\"; break;
            case '\n': out += "\\n";  break;
            case '\r': out += "\\r";  break;
            case '\t': out += "\\t";  break;
            default:
                if (c < 0x20) {
                    char escaped[8];
                    std::snprintf(escaped, sizeof(escaped), "\\u%04X", c);
                    out += escaped;
                } else {
                    out += static_cast<char>(c);
                }
        }
    }
    return out;
}

// Valid C++ identifier: non-alnum -> '_', never starts with a digit.
[[nodiscard]] inline std::string MakeIdentifier(const std::string& name) {
    std::string id = name;
    for (char& c : id) {
        if (!std::isalnum(static_cast<unsigned char>(c))) c = '_';
    }
    if (id.empty() || std::isdigit(static_cast<unsigned char>(id.front()))) id.insert(id.begin(), '_');
    return id;
}

[[nodiscard]] inline bool WriteJson(const std::filesystem::path& path, const Meta& meta,
                                    const Scanner::Layout& layout, const Scanner::DumpResult& dump) {
    std::ofstream out(path, std::ios::binary | std::ios::trunc);
    if (!out) return false;

    out << "{\n"
        << "    \"Meta\": {\n"
        << "        \"Process\": \"" << JsonEscape(meta.process) << "\",\n"
        << "        \"RobloxVersion\": \"" << JsonEscape(meta.robloxVersion) << "\",\n"
        << "        \"GeneratedAt\": \"" << meta.generatedAt << "\",\n"
        << "        \"ImageSize\": \"" << Memory::ToHex(meta.imageSize) << "\",\n"
        << "        \"FlagCount\": " << dump.flags.size() << "\n"
        << "    },\n"
        << "    \"FFlagOffsets\": {\n"
        << "        \"FFlagList\": \"" << Memory::ToHex(layout.mapGlobalRva) << "\",\n"
        << "        \"ValueGetSet\": \"" << Memory::ToHex(layout.valueGetSet) << "\",\n"
        << "        \"FlagToValue\": \"" << Memory::ToHex(layout.flagToValue) << "\"\n"
        << "    },\n"
        << "    \"FFlags\": {\n";

    bool first = true;
    for (const auto& [name, rva] : dump.flags) {
        if (!first) out << ",\n";
        first = false;
        out << "        \"" << JsonEscape(name) << "\": \"" << Memory::ToHex(rva) << '"';
    }
    out << "\n    }\n}\n";
    return out.good();
}

[[nodiscard]] inline bool WriteHeader(const std::filesystem::path& path, const Meta& meta,
                                      const Scanner::Layout& layout, const Scanner::DumpResult& dump) {
    std::ofstream out(path, std::ios::binary | std::ios::trunc);
    if (!out) return false;

    const auto hex = [](std::uintptr_t value) { return Memory::ToHex(value, /*upper=*/false); };

    out << "// Generated by RobloxFFlagDumper | " << meta.robloxVersion << " | " << meta.generatedAt << "\n"
        << "#pragma once\n"
        << "#include <cstdint>\n"
        << "#include <string_view>\n\n"
        << "namespace FFlagOffsets {\n"
        << "    inline constexpr std::string_view ClientVersion = \"" << JsonEscape(meta.robloxVersion) << "\";\n\n"
        << "    namespace FFlagList {\n"
        << "        inline constexpr std::uintptr_t Pointer = " << hex(layout.mapGlobalRva) << ";\n"
        << "        inline constexpr std::uintptr_t ToFlag = " << hex(layout.valueGetSet) << ";\n"
        << "        inline constexpr std::uintptr_t ToValue = " << hex(layout.flagToValue) << ";\n"
        << "    }\n\n"
        << "    namespace FFlags {\n";

    std::set<std::string> usedIdentifiers;
    for (const auto& [name, rva] : dump.flags) {
        const std::string id = MakeIdentifier(name);
        if (!usedIdentifiers.insert(id).second) continue;  // sanitised name collided
        out << "        inline constexpr std::uintptr_t " << id << " = " << hex(rva) << ";\n";
    }
    out << "    }\n"
        << "}\n";
    return out.good();
}

}  // namespace Output
